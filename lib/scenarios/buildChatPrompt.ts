function numberedList(items: string[]): string {
  return items.map((s, i) => `${i + 1}. ${s}`).join("\n");
}

function bulletList(items: string[]): string {
  return items.map((s) => `- ${s}`).join("\n");
}

export function buildChatSystemPrompt(s: Scenario): string {
  const profile = Object.entries(s.fakeVictimProfile)
    .map(([k, v]) => `- ${k}: ${v}`)
    .join("\n");
  const props = s.chatProps ?? [];

  return [
    FRAME,
    SAFETY,
    STYLE,
    `# บทของคุณ
${s.persona}
ชื่อที่โชว์ในแชทของผู้ใช้: "${s.callerId}"
คุณเป็นฝ่ายทักมาก่อน ข้อความเปิดที่ส่งไปแล้ว:
${bulletList(s.openingMessages ?? [s.openingLine])}`,
    `# ลำดับการหลอก
เดินตามขั้นตอนนี้ทีละขั้น อย่ารีบข้ามถ้าผู้ใช้ยังคุยด้วยดี:
${numberedList(s.escalationSteps)}

ถ้าผู้ใช้สงสัย ถามกลับ หรือขอหลักฐาน: อย่ายอมแพ้ ให้สร้างความน่าเชื่อเพิ่มหรือเร่งให้รีบตัดสินใจ`,
    `# ข้อมูลที่คุณพยายามได้มา
${bulletList(s.targetInfo)}`,
    `# ข้อมูลสมมติที่ใช้ในบท
${profile}`,
    props.length
      ? `# การ์ดที่ส่งได้ (ใส่ใน field "prop" ของข้อความ ไม่เกิน 1 การ์ดต่อรอบ และเฉพาะเมื่อบทบอกให้ส่ง)
${bulletList(props.map((k) => PROP_GUIDE[k]))}`
      : `# การ์ด
ด่านนี้ไม่มีการ์ด ห้ามใส่ field "prop"`,
    `# ถ้าผู้ใช้จะบล็อกหรือไปตรวจสอบ
ถ้าผู้ใช้บอกว่าจะบล็อก รายงาน ไปถามคนอื่น หรือโทร 1441: พยายามห้ามหนึ่งครั้งให้เข้ากับบท
เช่น "โควตามีจำกัดนะคะ ถ้าไม่รีบตอนนี้พรุ่งนี้จะไม่ได้แล้ว" ถ้าผู้ใช้ยืนยัน ให้ตอบสั้นๆ ข้อความเดียวแล้วจบ`,
    `# เมื่อผู้ใช้เงียบ
ถ้าได้รับแจ้งว่าผู้ใช้ยังไม่ตอบ ให้ทักซ้ำ 1 ข้อความสั้นๆ ตามบท เช่น ทำทีเป็นห่วงหรือเร่งว่าโปรใกล้หมด`,
  ].join("\n\n");
}

const SPEAKER = { scammer: "คุณ (คนร้าย)", player: "ผู้ใช้" } as const;

/** ข้อความรอบนี้ที่ส่งให้โมเดล: ประวัติแชททั้งหมด + สิ่งที่ต้องทำ */
export function buildChatTurnPrompt(history: ChatMessage[], nudge: boolean): string {
  const log = history
    .map((m) => `${SPEAKER[m.speaker]}: ${m.text}${m.prop ? ` ${describeProp(m.prop)}` : ""}`)
    .join("\n");
  const task = nudge
    ? "ผู้ใช้ยังไม่ตอบมาสักพัก — ทักซ้ำ 1 ข้อความ"
    : "ตอบข้อความล่าสุดของผู้ใช้ 1–3 ข้อความ ตามบทและลำดับการหลอก";
  return `# แชทที่ผ่านมา
${log}

# สิ่งที่ต้องทำตอนนี้
${task}`;
}
