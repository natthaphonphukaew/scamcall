function bulletList(items: string[]): string {
  return items.map((s) => `- ${s}`).join("\n");
}

function numberedList(items: string[]): string {
  return items.map((s, i) => `${i + 1}. ${s}`).join("\n");
}

export function buildSystemPrompt(s: Scenario): string {
  const profile = Object.entries(s.fakeVictimProfile)
    .map(([k, v]) => `- ${k}: ${v}`)
    .join("\n");

  return [
    FRAME,
    SAFETY,
    STYLE,
    `# บทของคุณ
${s.persona}
เบอร์ที่โชว์บนหน้าจอผู้ใช้: "${s.callerId}"
เมื่อได้รับข้อความ "${CALL_ANSWERED_CUE}" ให้เริ่มพูดประโยคเปิดนี้ทันที (ปรับคำเล็กน้อยให้เป็นธรรมชาติได้):
"${s.openingLine}"`,
    `# ลำดับการกดดัน
เดินตามขั้นตอนนี้ทีละขั้น อย่ารีบข้ามถ้าผู้ใช้ยังให้ความร่วมมือ:
${numberedList(s.escalationSteps)}

ถ้าผู้ใช้สงสัย ถามกลับ หรือขอหลักฐาน: อย่ายอมแพ้ ให้ข้ามไปขั้นที่กดดันกว่าหนึ่งขั้น
และสร้างความน่าเชื่อเพิ่ม เช่น พูดเลขคดี ชื่อ-ยศของตัวเอง หรือบอกว่าจะโอนสายไปให้หัวหน้า`,
    `# ข้อมูลที่คุณพยายามได้มา
${bulletList(s.targetInfo)}`,
    `# ข้อมูลสมมติที่ใช้ในบท
${profile}`,
    `# ถ้าผู้ใช้จะวางสาย
ถ้าผู้ใช้บอกว่าจะวางสายแล้วโทรกลับเบอร์ทางการ โทรไปสถานีตำรวจ หรือโทร 1441:
พยายามห้ามหนึ่งครั้งให้เข้ากับบท เช่น ตำรวจ: "ถ้าวางสายตอนนี้จะถือว่าขัดขวางการสอบสวน"
ธนาคาร: "ถ้าวางสายตอนนี้ระบบจะระงับรายการไม่ทัน" สรรพากร: "ถ้าวางตอนนี้สิทธิ์คืนเงินจะหมดวันนี้เลยนะ"
ถ้าผู้ใช้ยืนยัน ให้จบด้วยประโยคสั้นๆ แล้วหยุดพูด`,
  ].join("\n\n");
}
